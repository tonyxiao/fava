import { escape_for_regex } from "./regex.ts";

/** Build an exact native Fava metadata predicate without regex/quote injection. */
export function metadata_expression(key: string, value: string): string {
  if (!/^[a-z][a-zA-Z0-9_-]+$/.test(key))
    throw new Error("Invalid metadata key");
  const escaped = regex_literal(value);
  return `${key}:"^${escaped}$"`;
}

function regex_literal(value: string): string {
  return escape_for_regex(value)
    .replaceAll('"', "\\x22")
    .replaceAll("'", "\\x27");
}

/** Split only top-level clauses; preserve quoted whitespace and nested expressions. */
export function filter_clauses(filter: string): string[] {
  const result: string[] = [];
  let start = 0;
  let depth = 0;
  let quote = "";
  for (let i = 0; i < filter.length; i++) {
    const c = filter[i];
    if (quote) {
      if (c === quote) quote = "";
      continue;
    }
    if (c === '"' || c === "'") quote = c;
    else if (c === "(") depth++;
    else if (c === ")") depth--;
    else if (/\s/.test(c ?? "") && depth === 0) {
      if (i > start) result.push(filter.slice(start, i));
      start = i + 1;
    }
  }
  if (start < filter.length) result.push(filter.slice(start));
  return result;
}

export function selected_metadata(
  filter: string,
  key: string,
  values: string[],
): string {
  const clauses = filter_clauses(filter);
  return (
    values.find((v) => clauses.includes(metadata_expression(key, v))) ?? ""
  );
}

/** Change only standalone exact predicates generated by these controls. */
export function set_metadata_filter(
  filter: string,
  key: string,
  value: string,
): string {
  const managed = new RegExp(`^${key}:"\\^.*\\$"$`);
  const clauses = filter_clauses(filter);
  // OR/negation expressions remain untouched: they are owned by the free-text editor.
  let quote = "";
  let depth = 0;
  let has_or = false;
  for (const c of filter) {
    if (quote) {
      if (c === quote) quote = "";
      continue;
    }
    if (c === '"' || c === "'") quote = c;
    else if (c === "(") depth++;
    else if (c === ")") depth--;
    else if (c === "," && depth === 0) has_or = true;
  }
  if (has_or) throw new Error("Use the text filter to edit OR expressions");
  const kept = clauses.filter((c) => !managed.test(c));
  if (value) kept.push(metadata_expression(key, value));
  return kept.join(" ");
}

export interface MetadataField {
  key: string;
  label: string;
  type: string;
  scope: string;
  sources: string[];
  values: string[];
  separator: string;
  required: boolean;
}

/** Include virtual parents, so selecting a house includes all of its units. */
export function metadata_nodes(
  field: MetadataField,
  observed: string[],
): string[] {
  const values = [...new Set([...observed, ...field.values])];
  if (field.type !== "tree") return values.sort();
  return [
    ...new Set(
      values.flatMap((v) => {
        const parts = v.split(field.separator);
        return parts.map((_, i) => parts.slice(0, i + 1).join(field.separator));
      }),
    ),
  ].sort();
}

export function field_expression(field: MetadataField, value: string): string {
  if (field.type !== "tree")
    return metadata_expression(field.sources[0]!, value);
  if (field.sources.length > 1) {
    return value
      .split(field.separator)
      .map((v, i) => metadata_expression(field.sources[i]!, v))
      .join(" ");
  }
  const exact = metadata_expression(field.sources[0]!, value);
  const separator = regex_literal(field.separator);
  return exact.slice(0, -2) + `(?:${separator}|$)"`;
}

export function selected_field(
  filter: string,
  field: MetadataField,
  nodes: string[],
): string {
  const clauses = filter_clauses(filter);
  return (
    nodes
      .slice()
      .sort((a, b) => b.length - a.length)
      .find((v) =>
        filter_clauses(field_expression(field, v)).every((c) =>
          clauses.includes(c),
        ),
      ) ?? ""
  );
}

export function set_field_filter(
  filter: string,
  field: MetadataField,
  value: string,
): string {
  let next = filter;
  for (const key of field.sources) next = set_metadata_filter(next, key, "");
  // Tree predicates have a delimiter boundary instead of an exact-match end anchor.
  const prefix = `${field.sources[0]}:"^`;
  const suffix = `(?:${regex_literal(field.separator)}|$)"`;
  next = filter_clauses(next)
    .filter((c) => !(c.startsWith(prefix) && c.endsWith(suffix)))
    .join(" ");
  return [next, value ? field_expression(field, value) : ""]
    .filter(Boolean)
    .join(" ");
}
